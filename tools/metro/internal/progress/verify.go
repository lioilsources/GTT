package progress

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// VerifyPath holds how Ol1n checks the waiting items (Prompts/05 L-S14).
const VerifyPath = "plans/verify.yaml"

// Check is one item's walk-through on the phone.
type Check struct {
	City   string `yaml:"city"`
	Q      string `yaml:"q"`
	Expect string `yaml:"expect"`
	Min    int    `yaml:"min"`
	Client string `yaml:"client"` // w | f | decide
}

// VerifyFile is plans/verify.yaml.
type VerifyFile struct {
	PassMin int              `yaml:"pass_min"`
	Base    string           `yaml:"base"`
	Checks  map[string]Check `yaml:"checks"`
}

// LoadVerify reads plans/verify.yaml; a missing file means no walk-throughs.
func LoadVerify(root string) (*VerifyFile, error) {
	b, err := os.ReadFile(filepath.Join(root, VerifyPath))
	if os.IsNotExist(err) {
		return &VerifyFile{PassMin: 30}, nil
	}
	if err != nil {
		return nil, err
	}
	var v VerifyFile
	if err := yaml.Unmarshal(b, &v); err != nil {
		return nil, fmt.Errorf("%s: %w", VerifyPath, err)
	}
	if v.PassMin <= 0 {
		v.PassMin = 30
	}
	return &v, nil
}

var cityOrder = map[string]int{"nyc": 0, "prague": 1, "tokyo": 2, "": 3}
var cityNames = map[string]string{"nyc": "New York", "prague": "Praha", "tokyo": "Tokio", "": "kdekoli"}

type pass struct {
	city  string
	items []Item
	min   int
}

// Passes groups the waiting web checks by city (file order of the items inside a city) and cuts
// each city into passes of at most passMin minutes; an item longer than passMin gets its own pass.
func Passes(items []Item, v *VerifyFile) []pass {
	byCity := map[string][]Item{}
	for _, it := range items {
		c, ok := v.Checks[it.ID]
		if it.Status != Ceka || !ok || c.Client != "w" {
			continue
		}
		byCity[c.City] = append(byCity[c.City], it)
	}
	cities := make([]string, 0, len(byCity))
	for c := range byCity {
		cities = append(cities, c)
	}
	sort.Slice(cities, func(i, j int) bool { return cityOrder[cities[i]] < cityOrder[cities[j]] })
	var out []pass
	for _, c := range cities {
		cur := pass{city: c}
		for _, it := range byCity[c] {
			m := max(1, v.Checks[it.ID].Min)
			if cur.min > 0 && cur.min+m > v.PassMin {
				out = append(out, cur)
				cur = pass{city: c}
			}
			cur.items = append(cur.items, it)
			cur.min += m
		}
		if len(cur.items) > 0 {
			out = append(out, cur)
		}
	}
	return out
}

// RenderVerify writes docs/verify.md for the waiting items.
func RenderVerify(f *File, v *VerifyFile, date string) string {
	var b strings.Builder
	b.WriteString("# Ověřovací průchody pro Ol1na\n\nGENERATED by `metro progress` z `plans/progress.yaml` a `plans/verify.yaml`. Needitovat.\n")
	fmt.Fprintf(&b, "Stav k %s. „Ověřeno“ zapisuje session do `progress.yaml` jen po Ol1nově výslovném potvrzení.\n", date)
	link := func(c Check) string {
		if c.Q == "" {
			return "–"
		}
		u := v.Base + "?" + c.Q
		return fmt.Sprintf("[`?%s`](%s)", c.Q, u)
	}
	row := func(it Item) string {
		c := v.Checks[it.ID]
		return fmt.Sprintf("- [ ] **%s** %s · %s · %d min\n  %s\n", it.ID, it.Name, link(c), max(1, c.Min), c.Expect)
	}
	for i, p := range Passes(f.Items, v) {
		fmt.Fprintf(&b, "\n## Průchod %d · %s · %d min\n\n", i+1, cityNames[p.city], p.min)
		for _, it := range p.items {
			b.WriteString(row(it))
		}
	}
	var fOnly, decide, missing []Item
	for _, it := range f.Items {
		if it.Status != Ceka {
			continue
		}
		c, ok := v.Checks[it.ID]
		switch {
		case !ok:
			missing = append(missing, it)
		case c.Client == "f":
			fOnly = append(fOnly, it)
		case c.Client == "decide":
			decide = append(decide, it)
		}
	}
	if len(fOnly) > 0 {
		b.WriteString("\n## Jen aplikace (Flutter)\n\n")
		for _, it := range fOnly {
			b.WriteString(row(it))
		}
	}
	if len(decide) > 0 {
		b.WriteString("\n## Rozhodnutí a měření\n\n")
		for _, it := range decide {
			b.WriteString(row(it))
		}
	}
	if len(missing) > 0 {
		b.WriteString("\n## Bez návodu (doplnit do plans/verify.yaml)\n\n")
		for _, it := range missing {
			fmt.Fprintf(&b, "- [ ] **%s** %s\n", it.ID, it.Name)
		}
	}
	return b.String()
}
