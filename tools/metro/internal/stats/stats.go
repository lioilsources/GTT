// Commit is one commit on the first-parent history of the current branch.
type Commit struct {
	At      time.Time
	Subject string
}

var mergePR = regexp.MustCompile(`^Merge pull request #\d+ `)

// Timeline holds the commit-derived numbers.
type Timeline struct {
	First, Last time.Time
	Commits     int
	ActiveHours int // distinct clock hours with at least one commit
	MergedPRs   int
	PeakPRs     int // most PRs merged within one clock hour
	PeakHour    time.Time
}

// Summarize computes the timeline of commits (any order); merges count by their subject.
func Summarize(all []Commit, merges []Commit) Timeline {
	var t Timeline
	hours := map[time.Time]bool{}
	for _, c := range all {
		if t.First.IsZero() || c.At.Before(t.First) {
			t.First = c.At
		}
		if c.At.After(t.Last) {
			t.Last = c.At
		}
		hours[c.At.Truncate(time.Hour)] = true
	}
	t.Commits = len(all)
	t.ActiveHours = len(hours)
	per := map[time.Time]int{}
	for _, c := range merges {
		if !mergePR.MatchString(c.Subject) {
			continue
		}
		t.MergedPRs++
		h := c.At.Truncate(time.Hour)
		per[h]++
		if per[h] > t.PeakPRs || (per[h] == t.PeakPRs && h.Before(t.PeakHour)) {
			t.PeakPRs, t.PeakHour = per[h], h
		}
	}
	return t
}

// Kind of a source file for the line counts.
type Kind int

const (
	Manual Kind = iota
	Generated
	Test
)

var generatedPaths = []string{"packages/shared_gen/", "web/src/gen/", "app/lib/l10n/"}

// Classify returns the language (by extension, "" = not counted) and kind of a tracked path.
func Classify(path string) (lang string, kind Kind) {
	switch filepath.Ext(path) {
	case ".dart":
		lang = "Dart"
	case ".ts":
		lang = "TypeScript"
	case ".go":
		lang = "Go"
	case ".proto":
		lang = "Protobuf"
	case ".css":
		lang = "CSS"
	case ".py":
		lang = "Python"
	default:
		return "", Manual
	}
	for _, g := range generatedPaths {
		if strings.HasPrefix(path, g) {
			return lang, Generated
		}
	}
	if strings.HasSuffix(path, ".g.dart") || strings.HasSuffix(path, ".pb.go") || strings.HasSuffix(path, "_pb.ts") {
		return lang, Generated
	}
	if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "_test.dart") || strings.HasSuffix(path, ".test.ts") ||
		strings.Contains(path, "/test/") || strings.HasPrefix(path, "test/") {
		return lang, Test
	}
	return lang, Manual
}

// CityMilestones maps a city to the milestone that delivered it.
var CityMilestones = map[string]string{"nyc": "M2", "prague": "M3", "tokyo": "M4"}

func git(root string, args ...string) ([]byte, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git %s: %w", strings.Join(args, " "), err)
	}
	return out, nil
}

func parseLog(b []byte) []Commit {
	var out []Commit
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		at, subj, ok := strings.Cut(sc.Text(), "\t")
		if !ok {
			continue
		}
		t, err := time.Parse(time.RFC3339, at)
		if err == nil {
			out = append(out, Commit{At: t, Subject: subj})
		}
	}
	return out
}

// Render writes the STATS.md text from the repository at root.
func Render(root string) (string, error) {
	allB, err := git(root, "log", "--format=%aI\t%s")
	if err != nil {
		return "", err
	}
	mergeB, err := git(root, "log", "--first-parent", "--merges", "--format=%aI\t%s")
	if err != nil {
		return "", err
	}
	tl := Summarize(parseLog(allB), parseLog(mergeB))

	files, err := git(root, "ls-files")
	if err != nil {
		return "", err
	}
	lines := map[string][3]int{}
	for _, p := range strings.Split(strings.TrimSpace(string(files)), "\n") {
		lang, kind := Classify(p)
		if lang == "" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(root, p))
		if err != nil {
			continue
		}
		v := lines[lang]
		v[kind] += bytes.Count(b, []byte("\n"))
		lines[lang] = v
	}
	f, err := progress.Load(root)
	if err != nil {
		return "", err
	}
	counts := progress.Counts(root, f)

	var b strings.Builder
	b.WriteString("# Čísla projektu\n\nGENERATED by `metro stats`. Mimo měření postupu (pravidlo 6 v PROGRESS.md platí dál).\n\n")
	b.WriteString("## Historie\n\n| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| První commit | %s |\n| Poslední commit | %s |\n", tl.First.Format("2006-01-02 15:04"), tl.Last.Format("2006-01-02 15:04"))
	fmt.Fprintf(&b, "| Od prvního po poslední | %.1f h |\n", tl.Last.Sub(tl.First).Hours())
	fmt.Fprintf(&b, "| Hodiny s aspoň jedním commitem | %d |\n| Commity | %d |\n| Smergované PR | %d |\n", tl.ActiveHours, tl.Commits, tl.MergedPRs)
	if tl.PeakPRs > 0 {
		fmt.Fprintf(&b, "| Nejvíc PR za hodinu | %d (%s) |\n", tl.PeakPRs, tl.PeakHour.Format("2006-01-02 15:00"))
	}
	b.WriteString("\n## Řádky kódu\n\n| Jazyk | Ruční | Generované | Testy |\n|---|---|---|---|\n")
	langs := make([]string, 0, len(lines))
	for l := range lines {
		langs = append(langs, l)
	}
	sort.Slice(langs, func(i, j int) bool {
		a, c := lines[langs[i]], lines[langs[j]]
		return a[0]+a[1]+a[2] > c[0]+c[1]+c[2]
	})
	for _, l := range langs {
		v := lines[l]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", l, v[Manual], v[Generated], v[Test])
	}
	b.WriteString("\n## Obsah a testy\n\n| | |\n|---|---|\n")
	for _, k := range []string{"Města (s balíčkem)", "Minihry", "Auta", "Památky", "Skity", "Testy"} {
		fmt.Fprintf(&b, "| %s | %s |\n", k, counts[k])
	}
	b.WriteString("\n## Města: od prvního commitu po uzavření milníku\n\n| Město | Milník | První commit | Uzavřeno | Doba |\n|---|---|---|---|---|\n")
	cities := make([]string, 0, len(CityMilestones))
	for c := range CityMilestones {
		cities = append(cities, c)
	}
	sort.Strings(cities)
	for _, c := range cities {
		m := CityMilestones[c]
		fb, err := git(root, "log", "--reverse", "--format=%aI\t%s", "--", "content/cities/"+c)
		if err != nil {
			return "", err
		}
		cs := parseLog(fb)
		if len(cs) == 0 {
			continue
		}
		start := cs[0].At
		closed, ok := milestoneClosed(f, m)
		if !ok {
			fmt.Fprintf(&b, "| %s | %s | %s | otevřený | – |\n", c, m, start.Format("2006-01-02 15:04"))
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %.1f h |\n", c, m, start.Format("2006-01-02 15:04"), closed.Format("2006-01-02 15:04"), closed.Sub(start).Hours())
	}
	return b.String(), nil
}

// milestoneClosed: the latest done time of a milestone whose every item left todo/wip.
func milestoneClosed(f *progress.File, m string) (time.Time, bool) {
	var last time.Time
	n := 0
	for _, it := range f.Items {
		if it.Milestone != m {
			continue
		}
		n++
		if !it.Delivered() || it.Done == "" {
			return time.Time{}, false
		}
		t, err := time.ParseInLocation("2006-01-02T15:04", it.Done, time.Local)
		if err != nil {
			return time.Time{}, false
		}
		if t.After(last) {
			last = t
		}
	}
	return last, n > 0
}
