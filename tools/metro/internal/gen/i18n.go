package gen

import (
	"encoding/json"
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// TemplateLocale is the locale every other locale is checked against.
const TemplateLocale = "en"

var placeholderRe = regexp.MustCompile(`\{([a-zA-Z_][a-zA-Z0-9_]*)\}`)

type message struct {
	key, text string
	meta      *yaml.Node // "@key" entry, template locale only
}

func readLocale(path string) ([]message, error) {
	root, err := readOrdered(path)
	if err != nil {
		return nil, err
	}
	var msgs []message
	metas := map[string]*yaml.Node{}
	for i := 0; i+1 < len(root.Content); i += 2 {
		k, v := root.Content[i].Value, root.Content[i+1]
		if strings.HasPrefix(k, "@") {
			metas[strings.TrimPrefix(k, "@")] = v
			continue
		}
		if v.Kind != yaml.ScalarNode {
			return nil, fmt.Errorf("%s: %s must be a string", path, k)
		}
		msgs = append(msgs, message{key: k, text: v.Value})
	}
	for i := range msgs {
		msgs[i].meta = metas[msgs[i].key]
	}
	return msgs, nil
}

func placeholders(s string) []string {
	var out []string
	for _, m := range placeholderRe.FindAllStringSubmatch(s, -1) {
		out = append(out, m[1])
	}
	sort.Strings(out)
	return out
}

// I18n generates ARB files for Flutter and a typed message table for the web from i18n/*.json.
func I18n(o *Output, dir string) error {
	files, err := filepath.Glob(filepath.Join(o.Root, dir, "*.json"))
	if err != nil {
		return err
	}
	locales := map[string][]message{}
	var names []string
	for _, f := range files {
		loc := strings.TrimSuffix(filepath.Base(f), ".json")
		m, err := readLocale(f)
		if err != nil {
			return err
		}
		locales[loc] = m
		names = append(names, loc)
	}
	sort.Strings(names)
	tmpl, ok := locales[TemplateLocale]
	if !ok {
		return fmt.Errorf("i18n: %s.json (template) missing", TemplateLocale)
	}
	for _, loc := range names {
		have := map[string]string{}
		for _, m := range locales[loc] {
			have[m.key] = m.text
		}
		for _, m := range tmpl {
			t, ok := have[m.key]
			if !ok {
				return fmt.Errorf("i18n: %s.json misses %q", loc, m.key)
			}
			if strings.Join(placeholders(t), ",") != strings.Join(placeholders(m.text), ",") {
				return fmt.Errorf("i18n: %s.json %q has placeholders %v, template has %v", loc, m.key, placeholders(t), placeholders(m.text))
			}
		}
		if len(have) != len(tmpl) {
			return fmt.Errorf("i18n: %s.json has keys the template does not", loc)
		}
	}

	o.Own("packages/shared_gen/l10n")
	for _, loc := range names {
		var b strings.Builder
		b.WriteString("{\n")
		fmt.Fprintf(&b, "  \"@@locale\": %s,\n", strconv.Quote(loc))
		fmt.Fprintf(&b, "  \"@@x-generated\": %s", strconv.Quote("GENERATED by `metro gen` from i18n/"+loc+".json. Do not edit."))
		for _, m := range locales[loc] {
			fmt.Fprintf(&b, ",\n  %s: %s", jsonStr(m.key), jsonStr(m.text))
			if loc == TemplateLocale && m.meta != nil {
				var v any
				if err := m.meta.Decode(&v); err != nil {
					return err
				}
				mb, err := json.Marshal(v)
				if err != nil {
					return err
				}
				fmt.Fprintf(&b, ",\n  %s: %s", jsonStr("@"+m.key), mb)
			}
		}
		b.WriteString("\n}\n")
		o.Add(fmt.Sprintf("packages/shared_gen/l10n/app_%s.arb", loc), []byte(b.String()))
	}

	var ts strings.Builder
	ts.WriteString(Header("//", dir+"/*.json"))
	ts.WriteString("\nexport const locales = [")
	for i, loc := range names {
		if i > 0 {
			ts.WriteString(", ")
		}
		ts.WriteString(strconv.Quote(loc))
	}
	ts.WriteString("] as const;\nexport type Locale = (typeof locales)[number];\n\n")
	ts.WriteString("export type MessageKey =\n")
	for _, m := range tmpl {
		fmt.Fprintf(&ts, "  | %s\n", strconv.Quote(m.key))
	}
	ts.WriteString(";\n\nexport const messages: Record<Locale, Record<MessageKey, string>> = {\n")
	for _, loc := range names {
		fmt.Fprintf(&ts, "  %s: {\n", strconv.Quote(loc))
		for _, m := range locales[loc] {
			fmt.Fprintf(&ts, "    %s: %s,\n", m.key, jsonStr(m.text))
		}
		ts.WriteString("  },\n")
	}
	ts.WriteString(`};

/** Formats a message; {name} placeholders are replaced from args. */
export function t(locale: Locale, key: MessageKey, args: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g, (_, k: string) => String(args[k] ?? ` + "`{${k}}`" + `));
}
`)
	o.Add("web/src/gen/i18n.ts", []byte(ts.String()))
	return nil
}

func jsonStr(s string) string {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}
