// readOrdered parses JSON or YAML keeping key order (JSON is valid YAML).
func readOrdered(path string) (*yaml.Node, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(doc.Content) != 1 {
		return nil, fmt.Errorf("%s: empty document", path)
	}
	return doc.Content[0], nil
}

// colorARGB converts CSS hex (#RRGGBB or #RRGGBBAA) to 0xAARRGGBB.
func colorARGB(s string) (uint32, bool) {
	if !strings.HasPrefix(s, "#") || (len(s) != 7 && len(s) != 9) {
		return 0, false
	}
	v, err := strconv.ParseUint(s[1:], 16, 32)
	if err != nil {
		return 0, false
	}
	if len(s) == 7 {
		return 0xFF000000 | uint32(v), true
	}
	return uint32(v>>8) | uint32(v&0xFF)<<24, true
}

type token struct {
	path  []string
	node  *yaml.Node
	color bool
}

func flattenTokens(n *yaml.Node, path []string, out *[]token) error {
	switch n.Kind {
	case yaml.MappingNode:
		for i := 0; i+1 < len(n.Content); i += 2 {
			k := n.Content[i].Value
			if strings.HasPrefix(k, "$") {
				continue
			}
			if err := flattenTokens(n.Content[i+1], append(append([]string{}, path...), k), out); err != nil {
				return err
			}
		}
	case yaml.SequenceNode, yaml.ScalarNode:
		t := token{path: path, node: n}
		probe := n
		if n.Kind == yaml.SequenceNode && len(n.Content) > 0 {
			probe = n.Content[0]
		}
		if path[0] == "color" {
			if _, ok := colorARGB(probe.Value); !ok {
				return fmt.Errorf("design tokens: %s: %q is not a #RRGGBB(AA) colour", strings.Join(path, "."), probe.Value)
			}
			t.color = true
		}
		*out = append(*out, t)
	}
	return nil
}

// Tokens generates Dart constants, a TS object and CSS variables from design/tokens.json.
func Tokens(o *Output, src string) error {
	root, err := readOrdered(filepath.Join(o.Root, src))
	if err != nil {
		return err
	}
	var toks []token
	if err := flattenTokens(root, nil, &toks); err != nil {
		return err
	}
	var d, ts, css strings.Builder
	d.WriteString(Header("//", src))
	d.WriteString("\n/// Design tokens. Colours are 0xAARRGGBB ints so pure-Dart code can carry them;\n/// wrap them in `Color(...)` in Flutter.\nabstract final class Tokens {\n")
	ts.WriteString(Header("//", src))
	ts.WriteString("\n/** Design tokens; colours are CSS hex strings. */\nexport const tokens = {\n")
	fmt.Fprintf(&css, "/* GENERATED by `metro gen` from %s. Do not edit. */\n", src)
	css.WriteString(":root {\n")
	for _, t := range toks {
		name := Camel(strings.Join(t.path, "_"))
		cssName := "--" + strings.ToLower(strings.Join(kebab(t.path), "-"))
		switch {
		case t.node.Kind == yaml.SequenceNode:
			var dv, tv []string
			for _, it := range t.node.Content {
				if t.color {
					c, _ := colorARGB(it.Value)
					dv = append(dv, fmt.Sprintf("0x%08X", c))
				} else {
					dv = append(dv, it.Value)
				}
				tv = append(tv, jsLiteral(it))
			}
			typ := "List<double>"
			if t.color {
				typ = "List<int>"
			}
			fmt.Fprintf(&d, "  static const %s %s = [%s];\n", typ, name, strings.Join(dv, ", "))
			fmt.Fprintf(&ts, "  %s: [%s],\n", name, strings.Join(tv, ", "))
			for i, it := range t.node.Content {
				fmt.Fprintf(&css, "  %s-%d: %s;\n", cssName, i, it.Value)
			}
		case t.color:
			c, _ := colorARGB(t.node.Value)
			fmt.Fprintf(&d, "  static const int %s = 0x%08X;\n", name, c)
			fmt.Fprintf(&ts, "  %s: %s,\n", name, jsLiteral(t.node))
			fmt.Fprintf(&css, "  %s: %s;\n", cssName, t.node.Value)
		case t.node.Tag == "!!int" || t.node.Tag == "!!float":
			v := t.node.Value
			if !strings.Contains(v, ".") {
				v += ".0"
			}
			fmt.Fprintf(&d, "  static const double %s = %s;\n", name, v)
			fmt.Fprintf(&ts, "  %s: %s,\n", name, t.node.Value)
			unit := ""
			if t.path[0] == "font" || t.path[0] == "space" || t.path[0] == "radius" {
				unit = "px"
			}
			fmt.Fprintf(&css, "  %s: %s%s;\n", cssName, t.node.Value, unit)
		default:
			fmt.Fprintf(&d, "  static const String %s = '%s';\n", name, t.node.Value)
			fmt.Fprintf(&ts, "  %s: %s,\n", name, jsLiteral(t.node))
			fmt.Fprintf(&css, "  %s: %s;\n", cssName, t.node.Value)
		}
	}
	d.WriteString("}\n")
	ts.WriteString("} as const;\n")
	css.WriteString("}\n")
	o.Add("packages/shared_gen/lib/src/tokens.g.dart", []byte(d.String()))
	o.Add("web/src/gen/tokens.ts", []byte(ts.String()))
	o.Add("web/src/gen/tokens.css", []byte(css.String()))
	return nil
}

func kebab(path []string) []string {
	out := make([]string, len(path))
	for i, p := range path {
		var b strings.Builder
		for j, r := range p {
			if r >= 'A' && r <= 'Z' {
				if j > 0 {
					b.WriteByte('-')
				}
				r += 'a' - 'A'
			}
			b.WriteRune(r)
		}
		out[i] = b.String()
	}
	return out
}

func jsLiteral(n *yaml.Node) string {
	switch n.Tag {
	case "!!int", "!!float", "!!bool":
		return n.Value
	default:
		return strconv.Quote(n.Value)
	}
}
