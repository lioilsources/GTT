// Package parity renders the parity matrix (DUALSTACK 5.6).
package parity

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"metro/internal/repo"
)

type Row struct {
	ID        string            `yaml:"id"`
	Name      string            `yaml:"name"`
	Level     string            `yaml:"level"`
	Spec      string            `yaml:"spec"`
	Vectors   string            `yaml:"vectors"`
	Scenarios string            `yaml:"scenarios"`
	Lead      string            `yaml:"lead"`
	Web       string            `yaml:"web"`
	Flutter   string            `yaml:"flutter"`
	Checks    map[string]string `yaml:"checks"`
}

var Clients = []string{"flutter", "web"}

func (r Row) status(c string) string {
	if c == "web" {
		return r.Web
	}
	return r.Flutter
}

// Red reports why a row is red: a done client whose check fails (or is pending for a release).
func (r Row) Red(release bool) []string {
	var why []string
	for _, c := range Clients {
		if r.status(c) != "done" {
			continue
		}
		switch ch := r.Checks[c]; {
		case ch == "fail":
			why = append(why, c+" fails")
		case release && ch != "pass":
			why = append(why, c+" not checked")
		}
	}
	return why
}

func Load(root string) ([]Row, error) {
	b, err := os.ReadFile(filepath.Join(root, repo.Parity))
	if err != nil {
		return nil, err
	}
	var rows []Row
	if err := yaml.Unmarshal(b, &rows); err != nil {
		return nil, err
	}
	// Results written by the clients' test runs override the recorded checks.
	for _, c := range Clients {
		rb, err := os.ReadFile(filepath.Join(root, "build", "parity", c+".json"))
		if err != nil {
			continue
		}
		var res map[string]string
		if err := json.Unmarshal(rb, &res); err != nil {
			return nil, fmt.Errorf("build/parity/%s.json: %w", c, err)
		}
		for i := range rows {
			if v, ok := res[rows[i].ID]; ok {
				if rows[i].Checks == nil {
					rows[i].Checks = map[string]string{}
				}
				rows[i].Checks[c] = v
			}
		}
	}
	return rows, nil
}

// Report writes PARITY.md and returns the red rows.
func Report(root string, release bool) ([]string, error) {
	rows, err := Load(root)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Parity\n\nGENERATED by `metro parity report` from parity.yaml. Do not edit.\n\n")
	b.WriteString("| ID | Feature | Level | Lead | Flutter | Web | Spec |\n|---|---|---|---|---|---|---|\n")
	var red []string
	for _, r := range rows {
		cell := func(c string) string {
			s := r.status(c)
			if ch := r.Checks[c]; ch != "" {
				s += " · " + ch
			}
			return s
		}
		mark := ""
		if why := r.Red(release); len(why) > 0 {
			mark = " 🔴"
			red = append(red, fmt.Sprintf("%s %s: %s", r.ID, r.Name, strings.Join(why, ", ")))
		}
		fmt.Fprintf(&b, "| %s%s | %s | %s | %s | %s | %s | %s |\n", r.ID, mark, r.Name, r.Level, r.Lead, cell("flutter"), cell("web"), r.Spec)
	}
	return red, os.WriteFile(filepath.Join(root, "PARITY.md"), []byte(b.String()), 0o644)
}
