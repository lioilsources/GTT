#!/usr/bin/env python3
"""Native app icons from the shared art (specs/appicon.md "F na iOS", "F na Androidu").

Reads assets/ui/app_icon/<mode>.png, <mode>_fg.png, <mode>_bg.png (1024²) and writes
  ios/Runner/Assets.xcassets/AppIcon.appiconset/            primary icon = sunset (every size)
  ios/Runner/Assets.xcassets/AppIcon-<mode>.appiconset/     alternate icons (single 1024² image)
  android/app/src/main/res/mipmap-<dpi>/                    legacy PNGs + adaptive layers
  android/app/src/main/res/mipmap-anydpi-v26/               adaptive icon XML per mode
The default mode keeps the stock names (AppIcon, ic_launcher). The output is committed; rerun after
the art changes:  python3 app/tool/gen_app_icons.py   [needs Pillow]
"""
import json
from pathlib import Path

from PIL import Image, ImageDraw

APP = Path(__file__).resolve().parent.parent
SRC = APP.parent / "assets" / "ui" / "app_icon"
XCASSETS = APP / "ios" / "Runner" / "Assets.xcassets"
RES = APP / "android" / "app" / "src" / "main" / "res"

MODES = ["day", "night", "sunset", "teal", "japan"]
DEFAULT = "sunset"

# Android densities: legacy launcher icon (48 dp) and adaptive layer (108 dp) in pixels.
DENSITIES = {"mdpi": (48, 108), "hdpi": (72, 162), "xhdpi": (96, 216), "xxhdpi": (144, 324), "xxxhdpi": (192, 432)}
# Corner radius of the legacy (pre-API 26) icon as a share of its side.
LEGACY_RADIUS = 0.2


def resized(img: Image.Image, size: int) -> Image.Image:
    return img.resize((size, size), Image.LANCZOS)


def rounded(img: Image.Image, size: int) -> Image.Image:
    """The icon at `size` px with transparent rounded corners (mask drawn at 4× and scaled down)."""
    mask = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=round(size * 4 * LEGACY_RADIUS), fill=255)
    out = resized(img, size).convert("RGBA")
    out.putalpha(mask.resize((size, size), Image.LANCZOS))
    return out


def ios(mode: str, icon: Image.Image) -> None:
    if mode == DEFAULT:
        # Stock Flutter icon set: keep Contents.json, redraw every file it lists.
        folder = XCASSETS / "AppIcon.appiconset"
        for image in json.loads((folder / "Contents.json").read_text("utf-8"))["images"]:
            px = round(float(image["size"].split("x")[0]) * int(image["scale"].rstrip("x")))
            resized(icon, px).save(folder / image["filename"], optimize=True)
        return
    folder = XCASSETS / f"AppIcon-{mode}.appiconset"
    folder.mkdir(parents=True, exist_ok=True)
    name = f"AppIcon-{mode}-1024.png"
    icon.save(folder / name, optimize=True)
    contents = {
        "images": [{"filename": name, "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "xcode", "version": 1},
    }
    (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n", "utf-8")


def android(mode: str, icon: Image.Image, fg: Image.Image, bg: Image.Image) -> None:
    name = "ic_launcher" if mode == DEFAULT else f"ic_launcher_{mode}"
    for dpi, (legacy, layer) in DENSITIES.items():
        folder = RES / f"mipmap-{dpi}"
        folder.mkdir(parents=True, exist_ok=True)
        rounded(icon, legacy).save(folder / f"{name}.png", optimize=True)
        resized(bg, layer).save(folder / f"{name}_background.png", optimize=True)
        if mode == DEFAULT:
            # The car layer is the same in every mode: one shared foreground.
            resized(fg, layer).save(folder / "ic_launcher_foreground.png", optimize=True)
    folder = RES / "mipmap-anydpi-v26"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{name}.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by app/tool/gen_app_icons.py (specs/appicon.md). -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="@mipmap/{name}_background"/>\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        "</adaptive-icon>\n",
        "utf-8",
    )


def main() -> None:
    foregrounds = {(SRC / f"{m}_fg.png").read_bytes() for m in MODES}
    assert len(foregrounds) == 1, "the foreground differs between modes: generate one per mode"
    for mode in MODES:
        icon = Image.open(SRC / f"{mode}.png").convert("RGB")
        ios(mode, icon)
        android(mode, icon, Image.open(SRC / f"{mode}_fg.png").convert("RGBA"), Image.open(SRC / f"{mode}_bg.png").convert("RGB"))


if __name__ == "__main__":
    main()
